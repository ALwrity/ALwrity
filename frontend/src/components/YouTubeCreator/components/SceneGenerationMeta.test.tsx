import React from "react";
import "@testing-library/jest-dom";
import { render, screen } from "@testing-library/react";
import { SceneGenerationMeta } from "./SceneGenerationMeta";
import type { SceneBuildGeneration } from "../../../services/youtubeApi";

const generation: SceneBuildGeneration = {
  text_gateway: "llm_text_gen",
  configured_provider: "wavespeed",
  system_prompt: "You are a master YouTube scriptwriter.",
  user_prompt: "**VIDEO PLAN:**\nSummary: Budget travel tips",
  json_schema_applied: true,
  llm_called: true,
  scenes_reused_from_plan: false,
  custom_script_used: false,
};

describe("SceneGenerationMeta", () => {
  it("shows exact scene-build prompt", () => {
    render(<SceneGenerationMeta generation={generation} />);

    expect(screen.getByText("Exact prompt sent to the LLM (scene build)")).toBeInTheDocument();
    expect(screen.getByText(/Budget travel tips/)).toBeInTheDocument();
    expect(screen.getByText(/LLM called for scenes/)).toBeInTheDocument();
    expect(screen.getByText(/Gateway: llm_text_gen/)).toBeInTheDocument();
  });

  it("shows info when scenes were reused without LLM", () => {
    render(
      <SceneGenerationMeta
        generation={{
          ...generation,
          llm_called: false,
          scenes_reused_from_plan: true,
        }}
      />,
    );

    expect(screen.getByText(/Scenes reused from plan/)).toBeInTheDocument();
    expect(
      screen.getByText(/Scenes were not generated by the scene LLM on this run/),
    ).toBeInTheDocument();
  });

  it("renders nothing without generation metadata", () => {
    const { container } = render(<SceneGenerationMeta generation={null} />);
    expect(container).toBeEmptyDOMElement();
  });
});
